-- Fictional insurance dataset for SQL practice. No real people.

-- Edge cases: active policies (NULL end_date), NULL holder_age, tied premiums,

-- policies with no claims, NULL amount_approved for pending/denied claims, a duplicate

-- claim submission, double-posted payment rows (identical rows), NULL payment method.

CREATE TABLE policies (policy_id INTEGER, holder_age INTEGER, state VARCHAR, product VARCHAR, start_date DATE, end_date DATE, annual_premium DECIMAL(10, 2));

CREATE TABLE claims (claim_id INTEGER, policy_id INTEGER, claim_date DATE, claim_type VARCHAR, amount_claimed DECIMAL(12, 2), amount_approved DECIMAL(12, 2), status VARCHAR);

CREATE TABLE payments (payment_id INTEGER, policy_id INTEGER, payment_date DATE, amount DECIMAL(10, 2), method VARCHAR);

